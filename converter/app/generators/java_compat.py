_ACCESS_ERROR = '''package {package}.access;

/**
 * Maps VBA Err object behaviour onto thrown exceptions.
 *
 * ACCESS-RUNTIME: generated by the converter; manual edits will be overwritten.
 */
public final class AccessError {{

    private AccessError() {{}}

    public static void log(String where, RuntimeException e) {{
        System.err.println("[ACCESS-ERR] " + where + ": "
                + e.getMessage());
    }}

    public static int number(RuntimeException e) {{
        return e.hashCode();   // no direct Err.Number equivalent; see report
    }}
}}
'''


def emit_runtime_files(base_package: str, usage: RuntimeUsage) -> dict[str, str]:
    """Return access/*.java sources required by current usage."""
    pkg = base_package
    files: dict[str, str] = {}
    if usage.any():
        files["AccessRuntime.java"] = _ACCESS_RUNTIME.format(package=pkg)
        files["AccessDateFunctions.java"] = _ACCESS_DATE.format(package=pkg)
        # goto bridge + string helpers accompany every runtime package
        files["VbaGotoSignal.java"] = _VBA_GOTO_SIGNAL.format(package=pkg)
        files["AccessStrings.java"] = _ACCESS_STRINGS.format(package=pkg)
    if usage.error_handling:
        files["AccessError.java"] = _ACCESS_ERROR.format(package=pkg)
    if usage.query_functions:
        files["AccessQueryFunctions.java"] = _ACCESS_QUERY.format(package=pkg)
    return files
