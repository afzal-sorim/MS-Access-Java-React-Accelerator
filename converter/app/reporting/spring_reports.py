def generate_report_sources(
    definitions: Iterable[ReportDefinition],
    *,
    base_package: str = "com.generated.app",
    report_strategy: str = "pdf",
) -> tuple[dict[str, str], bool]:
    """Generate report Java sources.

    Returns ``(files, needs_pdf_dependency)`` where ``files`` maps a bare Java
    file name to its source.
    """
    generator = SpringReportGenerator(
        definitions, base_package=base_package, report_strategy=report_strategy
    )
    return generator.generate(), generator.needs_pdf_dependency
