"""Spring Boot report endpoint generator (spec sections 20, 43, 45).

Emits, for an application that has at least one convertible report:

    report/ReportDefinition.java   immutable descriptor (record)
    report/ReportRegistry.java     the generated catalogue: SQL + fields + params
    report/ReportService.java      executes via NamedParameterJdbcTemplate
    report/ReportRow.java          one result row, order preserved
    report/ReportData.java         rows + resolved definition
    report/CsvReportWriter.java    RFC 4180 CSV
    report/PdfReportWriter.java    OpenPDF tabular PDF with groups + totals
    report/ReportController.java   JSON / CSV / PDF endpoints

Design constraints this file honours:

  * Report SQL is generated, not user-supplied, and parameters are always
    bound through NamedParameterJdbcTemplate — never string-concatenated.
    A generated app must not ship a SQL-injection hole.
  * Only reports the converter could fully translate are registered. An
    UNSUPPORTED report is emitted as a comment in the registry, so the gap is
    visible in the generated source instead of silently missing.
  * The OpenPDF dependency is only added to pom.xml when a report exists,
    per spec section 29: "Every generated dependency should have an
    originating Access requirement."
"""
