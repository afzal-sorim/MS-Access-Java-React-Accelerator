SELECT CUM_VAL_TB.CUM_VAL_ID, CUM_VAL_TB.CUM_VAL_DATE, CUM_VAL_TB.CUM_VAL_NBR, CumulativeValue([CUM_VAL_DATE],"CUM_VAL_NBR",[CUM_VAL_NBR]) AS Cum_Value
FROM CUM_VAL_TB
GROUP BY CUM_VAL_TB.CUM_VAL_ID, CUM_VAL_TB.CUM_VAL_DATE, CUM_VAL_TB.CUM_VAL_NBR
ORDER BY CUM_VAL_TB.CUM_VAL_ID, CUM_VAL_TB.CUM_VAL_DATE;

